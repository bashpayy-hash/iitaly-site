import { resolve, dirname, extname } from 'node:path';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url),ts=require('typescript'),cache=new Map();
function load(file) {
  if(!extname(file))file+=existsSync(file+'.ts')?'.ts':'.json';
  if(cache.has(file))return cache.get(file);
  if(file.endsWith('.json'))return JSON.parse(readFileSync(file,'utf8'));
  const compiled={exports:{}};cache.set(file,compiled.exports);
  const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true,resolveJsonModule:true}}).outputText;
  new Function('require','module','exports',code)(name=>load(name.startsWith('@/')?resolve('src',name.slice(2)):resolve(dirname(file),name)),compiled,compiled.exports);
  return compiled.exports;
}
