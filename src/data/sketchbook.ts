/**
 * Развороты скетчбука городов.
 *
 * Подпись каждого разворота описывает то, что действительно нарисовано в
 * кадре, и ничего сверх этого. Это не придирка: по исходному ТЗ на
 * иллюстрации нельзя показывать неправильные названия — а подписать
 * безымянное побережье «Салерно» значит ровно это и сделать. Поэтому
 * город стоит только там, где он узнаётся в кадре (Рим, Венеция) или где
 * это регион целиком (Тоскана); три приморских кадра остаются побережьем
 * без приписанного им города.
 *
 * Факты в `note` — из тех же данных, что и карта (src/data/italy.ts,
 * REGION_FACTS и City.region), и привязаны к месту, а не к картинке:
 * там, где место безымянное, факт говорит о группе городов честно.
 */
export interface Plate {
  /**
   * Готовая страница разворота 3:2 из public/sketchbook: оттиск,
   * смонтированный по центру кремового листа (скрипт монтажа описан в
   * design/illustrations/README.md). Почему монтаж, а не кроп: кадры
   * исходников от 0.8 до 3.0 по пропорции, и обрезка под 3:2 срезала бы у
   * полосы Венеции половину гондол. А растягивать нельзя — изгиб режет
   * страницу фоном по X, и растянутый фон разъехался бы с плоской
   * страницей на первом же кадре переворота.
   */
  src: string;
  /** что изображено */
  title: string;
  /** место или регион — пусто не бывает, но города нет там, где его нет в кадре */
  place: string;
  /** одна строка по существу: чем это место интересно поступающему */
  note: string;
}

