/**
 * Растровые иллюстрации: только production-кропы, собранные из присланных
 * исходников (design/illustrations/source/*.png, в сборку не попадают).
 * Исходники не изменялись — кропы вырезаны из них и перекодированы.
 *
 * Из пяти присланных кадров в дело пошли два. Разбор — почему именно эти —
 * в design/illustrations/README.md; коротко: остальные несут
 * сгенерированный текст (выдуманные названия вузов, «UO"'», «AMALFI
 * TCRIORT», разъехавшиеся засечные буквы) либо неоновое свечение и тёмную
 * гамму, чужую для кремовой бумаги сайта.
 *
 * Для каждой иллюстрации — свой кадр под мобильный, а не сжатый
 * десктопный: у полосы Венеции на узком экране кадр тесный (гондолы и
 * солнце), иначе половина полосы превращается в пустую воду.
 */
export interface IllustrationSource {
  /** путь без расширения; рядом лежат .avif и .webp */
  base: string;
  width: number;
  height: number;
}

export interface IllustrationAsset {
  desktop: IllustrationSource;
  /** Отдельный кадр под узкий экран. Нет — значит иллюстрация на мобильном
   *  не показывается вовсе (тогда и файла под неё быть не должно). */
  mobile?: IllustrationSource;
  alt: string;
}

