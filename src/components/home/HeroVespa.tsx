"use client";

import { motion, useScroll, useTransform, type MotionValue } from "motion/react";
import { Vespa } from "@/components/Vespa";
import { useReducedMotion } from "@/components/motion/MotionProvider";

/**
 * Путь прокрутки в пикселях, на котором разыгрывается проезд.
 *
 * Величина не с потолка: на десктопе первый экран липкий, и лента
 * разделов накрывает Веспу примерно через 250–300px прокрутки. Если
 * растянуть движение на весь экран (пробовал 620), к моменту, когда
 * объект закроют, он успевает проехать меньше половины пути — приём
 * просто не виден. 340 укладывает почти весь проезд в то окно, пока
 * Веспа ещё на экране.
 *
 * На телефоне липкости нет, и та же величина работает по-другому, но
 * тоже верно: объект стоит ниже сгиба, входит в поле зрения примерно на
 * этой же прокрутке и едет ровно тогда, когда его видно.
 */
const TRAVEL = 340;

/**
 * Веспа как главный объект первого экрана.
 *
 * Раньше маскот жил здесь высотой 32px рядом с надзаголовком — размер
 * иконки, то есть декор. Теперь он стоит в нижней полосе экрана, крупно
 * и по центру, а набор выстроен над ним: объект несёт экран, а не
 * подписывает его.
 *
 * Стоит он не посреди пустой полосы, а на самой кромке купола — там, где
 * первый экран переходит в лист разделов (позиционирование и расчёт
 * смещения — в Hero.tsx). Раньше экран заканчивался собственной
 * чернильной линейкой, а купол шёл отдельной дугой ниже: две параллельные
 * кромки в полусотне пикселей друг от друга, и Веспа висела между ними
 * сама по себе — это и читалось как обрубок. Линейку сняли, кромка
 * осталась одна, и переход через неё держит объект.
 *
 * Дальше приём доигрывает прокрутка: экран закреплён (z-0), лист наезжает
 * на него сверху (z-10) — бумага поднимается и забирает Веспу снизу
 * вверх, пока та едет вперёд. Не обрыв, а въезд в следующую страницу.
 *
 * Движение привязано к прокрутке, а не к таймеру. Это важно: таймерная
 * анимация проигрывается один раз и мимо человека, который ещё читает
 * заголовок, а привязанная к скроллу — отвечает на его собственное
 * действие. Веспа едет вправо и слегка наклоняется, пока первый экран
 * уходит вверх.
 *
 * Считаются только transform и opacity, то есть композитные свойства:
 * прокрутка не вызывает ни пересчёта раскладки, ни перерисовки.
 *
 * reducedMotion не снимает пропы (см. Reveal — почему это опасно), а
 * схлопывает диапазоны: те же useTransform, но выходные значения
 * постоянны, и объект просто стоит на месте.
 */
function useRange(
  scrollY: MotionValue<number>,
  from: number,
  to: number,
  still: boolean,
) {
  return useTransform(scrollY, [0, TRAVEL], still ? [from, from] : [from, to]);
}

export function HeroVespa({ className = "" }: { className?: string }) {
  const reducedMotion = useReducedMotion();

  // Прогресс считается от прокрутки окна, а не от прямоугольника самой
  // секции. Так надо: на десктопе первый экран липкий (см. page.tsx), его
  // rect после прилипания перестаёт двигаться — и привязка к target
  // замерла бы на нуле, то есть Веспа не поехала бы вообще.
  const { scrollY } = useScroll();

  // Только сдвиг и наклон. Затухание по прокрутке здесь было ошибкой:
  // на десктопе его не видно (объект и так закрывает лента разделов), а
  // на телефоне Веспа остаётся на экране и гасла бы прямо на виду —
  // читается не как приём, а как не догрузившаяся картинка.
  const x = useRange(scrollY, 0, 120, reducedMotion);
  // Наклон меньше прежних 4°: точка вращения — заднее колесо, и на шве
  // каждый градус отрывает переднее от кромки примерно на 3px. При 4°
  // Веспа переставала касаться линии и начинала выглядеть висящей.
  const rotate = useRange(scrollY, 0, -2.5, reducedMotion);

  return (
    // Ширину задаёт вызывающая сторона (она же ставит объект на шов), а
    // картинка тянется на 100%: одна величина в одном месте.
    <div className={`pointer-events-none ${className}`}>
      <motion.div style={{ x, rotate }} className="origin-bottom-left">
        <Vespa pose="hero" priority className="h-auto w-full" />
      </motion.div>
    </div>
  );
}
