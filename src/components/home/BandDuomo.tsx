/**
 * Полоса «Италия шире Рима» — Дуомо в тумане, первая из двух
 * иллюстративных полос главной. Второй такой полосы, кроме ночной, на
 * сайте нет и не должно появиться.
 *
 * Кадр собран слоями, как в референсе: дальние шпили в дымке, силуэт
 * собора, передний план — балюстрада. Глубину даёт не перспектива, а
 * разная плотность тона на каждом слое: дальний почти растворён, ближний
 * почти чёрный. Это же делает кадр кинематографичным при нулевой
 * детализации — рисовать розетки и статуи не нужно, читается силуэт.
 *
 * Почему SVG, а не фотография. Аудитория на медленном канале, а полоса
 * идёт во всю ширину: фотография такого размера стоила бы сотни
 * килобайт и всё равно потребовала бы отдельных кропов под 390 и 1990.
 * Здесь вектор в несколько килобайт, резкий на любом экране.
 *
 * Карты внутри нет и быть не должно: она живёт целиком на /universities,
 * сюда ведёт только текстовая ссылка.
 */

/* Шпиль: игла на тонком стволе. Разброс высот задаётся на месте — ровный
   ряд одинаковых игл читается как забор, а не как собор. */
function Spire({ x, base, h, w = 7 }: { x: number; base: number; h: number; w?: number }) {
  return (
    <path d={`M${x - w} ${base} L${x - w} ${base - h * 0.45} L${x} ${base - h} L${x + w} ${base - h * 0.45} L${x + w} ${base} Z`} />
  );
}

