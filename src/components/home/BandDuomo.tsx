/* Шпили фасада: к центру выше, по краям ниже. Считаются, а не выписаны
   вручную — иначе при правке ширины собора ряд разъезжается.

   Первый вариант давал 15 коротких игл на широком фронтоне, и силуэт
   читался как амбар с флажками: у готики вертикаль должна побеждать
   горизонталь, а там она проигрывала втрое. Теперь игл вдвое больше, они
   вдвое выше и стоят плотнее — масса уходит вверх. */
const FACADE = Array.from({ length: 27 }, (_, i) => {
  const x = 462 + i * 20;
  const d = Math.abs(i - 13) / 13;
  return { x, h: 196 - d * 118 };
});

