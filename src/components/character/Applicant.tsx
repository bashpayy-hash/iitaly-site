/**
 * Абитуриент — единственный персонаж сайта.
 *
 * Кто это. Человек 16–18 лет с тонкой папкой-досье: не маскот бренда, не
 * талисман в шапке, а тот, ради кого сайт существует. Поэтому он живёт
 * ровно там, где речь о нём: край первого экрана, полоса шагов, пустой
 * квиз. Три появления, больше нет нигде — и на /universities его тоже нет,
 * карту населять некем.
 *
 * Как нарисован. Плоская чернильная графика: жирный контур одной толщины,
 * две-три заливки, никакого объёма, градиентов и полутонов. Заливки взяты
 * из палитры пятен (rosso — куртка, yolk — папка, крем — бумага и лицо),
 * то есть персонаж собран из тех же красок, что и страница, а не принесён
 * из чужой иллюстрации.
 *
 * Про цветовое поле. По референсу герой СИДИТ НА пятне, и пятно обрезает
 * ему ноги. Механика здесь простая и её надо знать при верстке: поле
 * рисуется ПОВЕРХ фигуры (z выше), а фигура заходит под него снизу. Если
 * положить поле под фигуру, ноги окажутся нарисованы на пятне, и приём
 * рассыпется — станет просто иллюстрацией на цветном фоне.
 *
 * Про голубя. В позе walk рядом идёт миланский голубь — спутник, а не
 * второй герой: он мельче в четыре раза, без своей заливки, одним
 * контуром. Ни в одной другой позе его нет.
 */

export type ApplicantPose = "peek" | "walk" | "sit";

const INK = "#1a1a1a";
const CREAM = "#f7ece6";
const ROSSO = "#b42318";
const YOLK = "#e2b441";

/* Одна толщина контура на весь набор. Разнотолщинность — первое, что
   выдаёт собранного из кусков персонажа. */
const S = 3.6;

const strokeProps = {
  stroke: INK,
  strokeWidth: S,
  strokeLinecap: "round" as const,
  strokeLinejoin: "round" as const,
};

/** Голова с волосами и лицом. Вынесена: во всех трёх позах она одна и та же. */
function Head({ x, y, tilt = 0 }: { x: number; y: number; tilt?: number }) {
  return (
    <g transform={`translate(${x} ${y}) rotate(${tilt})`}>
      <ellipse cx="0" cy="0" rx="27" ry="29" fill={CREAM} {...strokeProps} />
      {/* Волосы шапкой, с чёлкой на правый глаз — асимметрия даёт характер
         дешевле любой детализации. */}
      <path
        d="M-28 -6 C-30 -30 -14 -38 2 -38 C20 -38 29 -27 27 -7 C22 -16 12 -21 2 -20 C-4 -12 -14 -8 -28 -6 Z"
        fill={INK}
        {...strokeProps}
      />
      <circle cx="-11" cy="2" r="2.6" fill={INK} />
      <circle cx="11" cy="2" r="2.6" fill={INK} />
      {/* Рот — короткая дуга. Не улыбка до ушей: человек сосредоточен, а не
         рекламно счастлив. */}
      <path d="M-6 13 Q0 17 7 12" fill="none" {...strokeProps} strokeWidth={S * 0.8} />
    </g>
  );
}

/** Папка-досье. Тонкая — в ней ещё почти ничего нет, это начало пути. */
function Folder({ x, y, rotate = 0 }: { x: number; y: number; rotate?: number }) {
  return (
    <g transform={`translate(${x} ${y}) rotate(${rotate})`}>
      <rect x="-22" y="-28" width="44" height="56" rx="3" fill={YOLK} {...strokeProps} />
      {/* Корешок и два листа, торчащих из папки. */}
      <path d="M-22 -14 H22" fill="none" {...strokeProps} strokeWidth={S * 0.7} />
      <path d="M-13 -33 H15 V-28 H-13 Z" fill={CREAM} {...strokeProps} strokeWidth={S * 0.7} />
    </g>
  );
}

function Pigeon({ x, y }: { x: number; y: number }) {
  return (
    <g transform={`translate(${x} ${y})`}>
      {/* Заливка, а не один контур: контуром на обсидиане голубя не было
         видно вовсе. Светлое пятно размером с ладонь читается и там. */}
      <path
        d="M-16 6 C-16 -4 -8 -10 0 -10 C7 -10 13 -6 15 0 L22 3 L14 6 C11 11 5 14 -2 14 C-10 14 -16 11 -16 6 Z"
        fill={CREAM}
        {...strokeProps}
        strokeWidth={S * 0.75}
      />
      <circle cx="8" cy="-4" r="1.8" fill={INK} />
      <path d="M-8 14 V20 M2 14 V20" fill="none" {...strokeProps} strokeWidth={S * 0.6} />
    </g>
  );
}

/**
 * peek — выглядывает снизу, опираясь локтями о кромку.
 *
 * Первая версия этой позы держалась за кромку двумя кистями, нарисованными
 * кремовой заливкой по краям плеч. На тёмном низу неба кремовые пятна по
 * бокам головы читались не как руки, а как рога — приём разваливался
 * ровно в том месте, ради которого затевался. Теперь руки сложены перед
 * собой одной формой того же цвета, что куртка: силуэт остаётся цельным,
 * и ни одна светлая деталь не висит отдельно от фигуры.
 */
function PosePeek() {
  return (
    <svg viewBox="0 0 200 132" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden>
      <g transform="translate(100 0)">
        {/* Плечи. Ниже кромки ничего не нарисовано вовсе — обрезка
           настоящая, а не маска поверх. */}
        <path
          d="M-52 132 V108 C-52 92 -30 82 0 82 C30 82 52 92 52 108 V132 Z"
          fill={ROSSO}
          {...strokeProps}
        />
        <Head x={0} y={50} tilt={-5} />
        {/* Сложенные руки — одна дуга поперёк плеч, того же цвета, что
           куртка; кисти намечены двумя короткими штрихами, не заливкой. */}
        <path d="M-44 122 C-30 110 30 110 44 122" fill={ROSSO} {...strokeProps} />
        <path d="M-12 116 h6 M6 116 h6" fill="none" {...strokeProps} strokeWidth={S * 0.7} />
      </g>
    </svg>
  );
}

/** walk — идёт вперёд с папкой под мышкой, рядом голубь. */
function PoseWalk() {
  return (
    <svg viewBox="0 0 220 260" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden>
      {/* Ноги — под корпусом, чтобы контур корпуса лёг поверх стыка.
         Заливка кремовая, не чернильная. Чернила здесь пробовались
         первыми и провалились ровно там, где эта поза и стоит: на
         обсидиановой полосе воронки #1a1a1a на #0f1011 не отличить, ноги
         исчезали, и над золотым пятном висел один торс. Светлая штанина
         читается на обоих фонах — и на тёмной полосе, и на белом. */}
      <g>
        <rect x="74" y="162" width="21" height="78" rx="10" fill={CREAM} {...strokeProps} transform="rotate(-5 84 200)" />
        <rect x="107" y="162" width="21" height="74" rx="10" fill={CREAM} {...strokeProps} transform="rotate(8 118 200)" />
      </g>
      {/* Корпус. */}
      <path
        d="M66 178 V116 C66 96 80 84 100 84 C120 84 134 96 134 116 V178 Z"
        fill={ROSSO}
        {...strokeProps}
      />
      <Head x={100} y={50} />
      {/* Дальняя рука отведена назад, ближняя прижимает папку. */}
      <path d="M68 118 C54 130 50 146 54 160" fill="none" {...strokeProps} strokeWidth="13" />
      <path d="M132 118 C146 128 150 142 148 156" fill="none" {...strokeProps} strokeWidth="13" />
      <Folder x={150} y={170} rotate={8} />
      {/* Ботинки поверх штанин, чернилами. Ниже линии обрезки цветовым
         полем — их видно только там, где поля нет. */}
      <g fill={INK}>
        <rect x="60" y="232" width="34" height="13" rx="6" />
        <rect x="118" y="228" width="34" height="13" rx="6" />
      </g>
      {/* Голубь стоит ровно на линии обрезки цветовым полем (y≈222 в этой
         системе координат): лапы приходятся на верхнюю кромку пятна, и он
         читается сидящим на ней. На y=232, как было сначала, поле
         закрывало его целиком — спутник существовал только в коде. */}
      <Pigeon x={46} y={202} />
    </svg>
  );
}

/** sit — сидит с раскрытой папкой на коленях. Поза ожидания: пустой квиз. */
function PoseSit() {
  return (
    <svg viewBox="0 0 220 200" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden>
      {/* Скрещённые ноги одной плотной формой — детализация здесь только
         мешала бы, фигура и так мелкая. */}
      <path
        d="M56 186 C56 168 78 158 110 158 C142 158 164 168 164 186 Z"
        fill={INK}
        {...strokeProps}
      />
      <path
        d="M76 162 V120 C76 102 88 92 110 92 C132 92 144 102 144 120 V162 Z"
        fill={ROSSO}
        {...strokeProps}
      />
      <Head x={110} y={58} tilt={5} />
      <path d="M78 124 C64 136 64 150 74 156" fill="none" {...strokeProps} strokeWidth="12" />
      <path d="M142 124 C156 136 156 150 146 156" fill="none" {...strokeProps} strokeWidth="12" />
      {/* Папка раскрыта — две створки домиком на коленях. */}
      <path d="M74 158 L110 140 L146 158 Z" fill={YOLK} {...strokeProps} />
      <path d="M110 140 V158" fill="none" {...strokeProps} strokeWidth={S * 0.7} />
    </svg>
  );
}

const POSES: Record<ApplicantPose, () => React.JSX.Element> = {
  peek: PosePeek,
  walk: PoseWalk,
  sit: PoseSit,
};

export function Applicant({ pose, className = "" }: { pose: ApplicantPose; className?: string }) {
  const Pose = POSES[pose];
  // aria-hidden на самой svg внутри позы: персонаж ничего не сообщает
  // сверх текста рядом, и озвучивать его скринридеру значит только
  // мешать. Обёртка не получает role="img" по той же причине.
  return (
    <div aria-hidden className={`pointer-events-none select-none ${className}`}>
      <Pose />
    </div>
  );
}
