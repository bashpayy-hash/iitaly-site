import { Vespa } from "@/components/Vespa";

/**
 * Полоса ожидания: пока файл читается и пока идёт сверка — веспа едет.
 *
 * Иллюстрация — та же самая, что стояла здесь неподвижно:
 * `/mascot/source/mascot-documents.svg` через компонент Vespa. Ни 3D, ни
 * Lottie, ни новой нейро-веспы: движение добавлено существующей картинке,
 * а не вместо неё.
 *
 * Веспа едет по СВОЕЙ полосе под строкой, а не поверх текста. Если пустить
 * её через всю плашку, она четыре секунды из пяти закрывает собой то
 * единственное, что здесь написано — сколько ждать. Полоса решает и второе:
 * у движения появляется дорога, и оно читается как поездка, а не как
 * дрейфующая картинка.
 *
 * Механика — CSS keyframes на трёх слоях, без canvas, WebGL и
 * requestAnimationFrame:
 *   .vespa-lane-track — проезд по X (проценты берутся от ширины полосы);
 *   .vespa-bob        — покачивание кузова на 2px;
 *   .vespa-dust       — три точки пыли позади, с разной задержкой.
 * Три слоя, потому что transform у элемента один: смешать проезд и
 * покачивание в одной анимации значит пересчитывать их вручную в каждом
 * кадре keyframes.
 *
 * Остановка не выражена отдельным состоянием: полоса живёт только на
 * шагах reading и checking. Как только проверка кончилась — успехом или
 * ошибкой — полоса размонтируется вместе с анимацией, и её место занимает
 * результат. Держать её после ответа ради кадра «доехал и встал» значило
 * бы оставить над результатом мультик, ради которого человек только что
 * ждал двадцать секунд.
 *
 * При prefers-reduced-motion остаётся один текст: правило в globals.css
 * снимает все три анимации и убирает полосу дороги.
 */
export function VespaRide({ text }: { text: string }) {
  return (
    /* Слабая подложка, а не прозрачность насквозь: за полосой стоит фото
       ночных облаков, и тёмно-красная веспа на тёмных облаках пропадает.
       0.04 белого достаточно, чтобы отделить дорогу от неба, и мало,
       чтобы полоса стала карточкой. */
    <div className="border border-white/15 bg-white/[0.04] px-4 py-3">
      <p className="text-apple-body-sm text-cloud-body">{text}</p>

      {/* aria-hidden: строка выше уже сказала всё, что нужно знать, и
         озвучивать скринридеру едущую картинку незачем. */}
      <div aria-hidden className="vespa-lane relative mt-2.5 h-9 overflow-hidden">
        <div className="vespa-lane-track absolute inset-0">
          <div className="vespa-bob absolute top-1/2 left-0 -translate-y-1/2">
            <span className="vespa-dust" />
            <span className="vespa-dust" />
            <span className="vespa-dust" />
            <Vespa pose="documents" className="relative h-9 w-auto" />
          </div>
        </div>
      </div>
    </div>
  );
}
