"use client";

import { useSearchParams } from "next/navigation";

/**
 * Показывает фразу, с которой человек пришёл из первого экрана.
 *
 * Зачем отдельным компонентом. useSearchParams заставляет ветку дерева
 * рендериться на клиенте, и при статическом экспорте сборка требует над
 * ней границу Suspense. Если позвать хук прямо в PlanExplorer, на клиент
 * уедет весь квиз целиком; здесь на клиент уходит один абзац.
 *
 * Текст показывается как цитата и никуда не отправляется: он не попадает
 * ни в лид, ни в аналитику. Бэкенд-контракты этот проход не трогает, а
 * отправлять свободный текст пользователя в запрос «на всякий случай» —
 * это собирать данные без причины.
 */
export function PlanSeed() {
  const q = useSearchParams().get("q")?.trim();
  if (!q) return null;

  return (
    <p className="mx-auto mt-6 max-w-lg border-l-2 border-rosso pl-4 text-left font-apple-text text-apple-body-sm text-graphite">
      Ты написал: «{q.slice(0, 200)}». Учтём это в плане — ответь ещё на
      несколько вопросов ниже.
    </p>
  );
}
