/** Объяснения незнакомых слов, которые встречаются в тексте (не больше `limit`). */
export function plainTerms(text: string, limit = 2): { term: string; plain: string }[] {
  if (!text) return [];
  return TERMS.filter(item => item.pattern.test(text)).slice(0, limit).map(({ term, plain }) => ({ term, plain }));
}

/** Подпись главной кнопки шага: что именно случится по нажатию. */
export function stepActionLabel(data: PortalData, task: PortalTask): string {
  if (task.id === "profile") return "Ответить на вопросы";
  if (task.id === "shortlist") return "Выбрать вузы";
  if (DOC_TASKS[task.id]) return data.docs?.[task.id] ? "Открыть итог проверки" : "Как подготовить";
  return "Как сделать";
}
