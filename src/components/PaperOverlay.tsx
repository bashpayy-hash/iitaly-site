/**
 * Постоянная бумажная плёнка на всё приложение.
 *
 * Лежит fixed поверх всего контента (включая хедер и карточки), потому что
 * материал не может «заканчиваться» на границе секции — иначе карточки и
 * формы выглядят как наклейки из другой системы. Поэтому же слой самый
 * слабый из трёх (5.5%): на карточках и в формах фактура должна
 * чувствоваться при близком рассмотрении, но не спорить с текстом. Секции,
 * которым нужна плотная фактура, добавляют свой слой поверх бумаги, но под
 * контентом — см. EditorialBackground (grain).
 *
 * z-index 70: выше секций и хедера (z-50), ниже чата и модалок (z-90/100) —
 * над панелью чата плёнка не нужна, у неё своя тёмная поверхность.
 * Без mix-blend-mode: фиксированный слой с блендом на весь вьюпорт
 * заставляет браузер пересчитывать композицию всей страницы на каждом
 * кадре скролла; здесь достаточно обычной альфы.
 */
export function PaperOverlay() {
  return (
    <div
      aria-hidden
      className="paper-layer paper-layer-global pointer-events-none fixed inset-0 z-[70]"
    />
  );
}
